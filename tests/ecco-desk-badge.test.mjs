import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from '../desk/node_modules/jsdom/lib/api.js';
const dom=new JSDOM('<!doctype html><head></head><body><div id="workspace-community-controls"></div></body>',{url:'https://ecco-ai-labs.github.io/ecco-studio/',runScripts:'outside-only'});
const w=dom.window;
Object.defineProperty(w.document,'currentScript',{value:{src:'https://ecco-ai-labs.github.io/ecco-studio/ecco-desk.js'}});
w.navigate=()=>{};w.page='welcome';w.EccoAuth={user:{id:'alice'}};
w.AbortSignal=globalThis.AbortSignal;w.setInterval=()=>1;
w.sessionStorage.setItem('ecco-user-session','alice-session');
let count=2,hold=false,release;const requests=[];
w.fetch=async(url,options)=>{requests.push({url,options});if(hold)return new Promise(resolve=>{release=()=>resolve({ok:true,json:async()=>({unreadTickets:8})})});return {ok:true,json:async()=>({unreadTickets:count})}};
w.eval(fs.readFileSync(new URL('../ecco-desk.js',import.meta.url),'utf8'));
const tick=()=>new Promise(r=>setTimeout(r,10));await tick();
const button=w.document.querySelector('#workspace-support'),badge=button.querySelector('.desk-response-badge');
assert.equal(badge.hidden,false);assert.equal(badge.textContent,'2');assert.match(button.title,/Support has responded on 2 tickets/);
assert(requests.every(r=>r.url.endsWith('/api/desk/support?notifications=1')));
count=1;w.document.dispatchEvent(new w.Event('ecco:desk-unread-change'));await tick();assert.equal(badge.textContent,'1');
count=0;w.document.dispatchEvent(new w.Event('ecco:desk-unread-change'));await tick();assert.equal(badge.hidden,true);
hold=true;w.document.dispatchEvent(new w.Event('ecco:desk-unread-change'));await tick();
w.EccoAuth.user=null;w.sessionStorage.removeItem('ecco-user-session');w.document.dispatchEvent(new w.Event('ecco:auth-change'));release();await tick();
assert.equal(badge.hidden,true);assert.equal(button.getAttribute('aria-label'),'Technical support');
dom.window.close();console.log('PASS: ticket-count badge, read refresh, zero state and stale identity isolation.');
